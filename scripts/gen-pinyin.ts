// 生成 lib/hanzi/pinyin-map.ts
// 用词库上下文消歧多音字；无词上下文的字用手工覆盖表 + pinyin-pro 默认读音
import { pinyin } from "pinyin-pro";
import { CHAR_SPLITS, WHOLE_CHARS } from "../lib/hanzi/characters";
import { WORD_BANK } from "../lib/hanzi/words";
import { writeFileSync } from "fs";

const chars = new Set<string>([...Object.keys(CHAR_SPLITS), ...WHOLE_CHARS]);

// 字 -> 包含它的词（上下文消歧）
const charWord: Record<string, string[]> = {};
for (const w of WORD_BANK) {
  for (const ch of w.word) {
    if (chars.has(ch)) {
      (charWord[ch] ??= []).push(w.word);
    }
  }
}

// 手工多音字覆盖（字库中出现的常见多音字，选小学常用读音）
const OVERRIDES: Record<string, string> = {
  都: "dōu",
  觉: "jiào",
  好: "hǎo",
  乐: "lè",
  长: "cháng",
  行: "xíng",
  得: "de",
  地: "de",
  了: "le",
  干: "gàn",
  和: "hé",
  给: "gěi",
  发: "fā",
  只: "zhǐ",
  奇: "qí",
  种: "zhǒng",
  转: "zhuǎn",
  重: "zhòng",
  相: "xiāng",
  还: "hái",
  教: "jiāo",
  空: "kōng",
  着: "zhe",
  便: "biàn",
  切: "qiē",
  弹: "dàn",
  当: "dāng",
  兴: "xīng",
  少: "shǎo",
  背: "bèi",
};

const map: Record<string, string> = {};
const missing: string[] = [];

for (const ch of chars) {
  let py: string | undefined;
  if (OVERRIDES[ch]) {
    py = OVERRIDES[ch];
  } else {
    const words = charWord[ch];
    if (words && words.length > 0) {
      // 用词消歧：整词拼音中取该字位置
      const w = words[0];
      const arr = pinyin(w, { toneType: "symbol", type: "array" });
      const idx = w.indexOf(ch);
      if (arr[idx]) py = arr[idx];
    }
    if (!py) {
      const arr = pinyin(ch, { toneType: "symbol", type: "array" });
      py = arr[0];
    }
  }
  if (py) {
    map[ch] = py;
  } else {
    missing.push(ch);
  }
}

const lines = Object.entries(map)
  .sort(([a], [b]) => a.localeCompare(b, "zh"))
  .map(([ch, py]) => `  ${JSON.stringify(ch)}: ${JSON.stringify(py)},`);

const out = `// AUTO-GENERATED by scripts/gen-pinyin.ts — 字库拼音映射（词上下文消歧）
export const CHAR_PINYIN: Record<string, string> = {
${lines.join("\n")}
};
`;

writeFileSync("lib/hanzi/pinyin-map.ts", out);
console.log(`生成完成: ${Object.keys(map).length} 字`);
if (missing.length) console.log("缺失:", missing.join(","));